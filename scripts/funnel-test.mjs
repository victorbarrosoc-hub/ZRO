import { chromium } from "playwright";
const out = process.argv[2] ?? (await import("node:os")).tmpdir();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:3000/orcamento", { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/funil-1.png` });
await page.getByRole("radio", { name: /Campanha/ }).click();
await page.waitForTimeout(900);
await page.getByLabel("Empresa ou marca").fill("Clínica Teste");
await page.getByLabel("Segmento").fill("Saúde");
await page.getByLabel("A ideia ou o objetivo").fill("Lançamento da nova unidade.");
await page.screenshot({ path: `${out}/funil-2.png` });
await page.getByRole("button", { name: "Continuar" }).click();
await page.waitForTimeout(700);
await page.getByLabel("Quando").fill("novembro de 2026");
await page.getByLabel("Cidade").fill("Natal/RN");
await page.getByRole("button", { name: "Continuar" }).click();
await page.waitForTimeout(700);
await page.getByRole("radio", { name: "2 diárias" }).click();
await page.waitForTimeout(900);
await page.getByRole("radio", { name: "2 a 4 vídeos" }).click();
await page.getByRole("radio", { name: "Horizontal e vertical" }).click();
await page.screenshot({ path: `${out}/funil-videos.png` });
await page.getByRole("button", { name: "Continuar" }).click();
await page.waitForTimeout(700);

import { chromium } from "playwright";
import { readFileSync } from "node:fs";
const creds = readFileSync("data/credenciais-dev.txt", "utf8").split("\n").filter((l) => l.includes("@"))[0].trim().split(/\s+/);
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto("http://localhost:3000/painel", { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/login-mobile.png` });
// senha errada
await page.fill("#email", creds[0]);
await page.fill("#password", "errada");
await page.click("button[type=submit]");
await page.waitForTimeout(1500);
console.log("erro exibido:", await page.locator("[role=alert]").last().innerText());
await page.fill("#password", creds[1]);
await page.click("button[type=submit]");
await page.waitForURL("**/painel", { timeout: 15000 });
console.log("url após login:", page.url(), "| texto:", await page.locator("main").innerText());
await browser.close();
if (errors.length) console.log("ERROS:", errors);
